    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombreUsuario = nombre.getText();
        String apellidoUsuario = apellido.getText();
        String emailUsuario = email.getText();
        String loginUsuario = loginname.getText();
        int nivelUsuario = nivelAcceso.getSelectedIndex();
        String passwordUsuario = password.getText();
        String data  = nombreUsuario + " "+ apellidoUsuario+ " "+ emailUsuario+
                " "+ loginUsuario+ " "+ nivelUsuario+ " "+ passwordUsuario;
        try{
            FileWriter fw=new FileWriter("usuario.txt");
            fw.write(data);
            fw.write(97);
            fw.close(); 
            FileReader fr=new FileReader("usuario.txt");
            int valor=fr.read();
            while(valor!=-1){
                System.out.print((char)valor);
                valor=fr.read();
            }
            fr.close();
        }
        catch(IOException e){
            System.out.println("Error E/S: "+e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

